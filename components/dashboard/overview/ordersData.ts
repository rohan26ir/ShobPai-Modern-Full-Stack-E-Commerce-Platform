// Shared demo orders and helpers matching the official order data
export const getCustomerAvatar = (order: any) => {
  if (order?.user?.photoURL) return order.user.photoURL;
  const name =
    order?.user?.displayName || order?.guestName || order?.user?.email || "customer";
  const seed = encodeURIComponent(String(name).trim());
  return `https://api.dicebear.com/7.x/avataaars/svg?seed=${seed}&backgroundColor=b6e3f4,c0aede,d1d4f9,ffd5dc,ffdfbf`;
};

